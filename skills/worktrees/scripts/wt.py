    s.add_argument("--branch", help="default: the task name")
    s.add_argument("--base", help="default: each repository's origin/HEAD")
    s.add_argument("--note", help="one line on what the task is, for its CLAUDE.md")
    s.add_argument("--extra", action="append", help="SRC[:DEST] - a file or folder copied into the task folder")
    s.add_argument("--build", action="append", help="the task's build command, run in the task folder (repeatable)")
    s.add_argument("--test", action="append", help="the task's test command, run in the task folder (repeatable)")

    s = sub.add_parser("restore")
    s.add_argument("manifest")
    s.add_argument("--as", dest="as_task", help="another task name")
    s.add_argument("--no-fetch", action="store_true")

    s = sub.add_parser("add")
    s.add_argument("task")
    repos_args(s)

    s = sub.add_parser("pin")
    s.add_argument("task")
