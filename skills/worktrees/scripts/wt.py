def cmd_prune(cfg, a):
    root = root_of(cfg)
    done, check, untouched = [], [], []
    for t in all_tasks(root):
        s = task_state(root, t, not a.no_fetch)
        edits = {r["state"] for r in s["repos"].values() if r["role"] == "edit"}
        deps_hold = any(holds_work(r) for r in s["repos"].values() if r["role"] == "dependency")
        if edits and edits <= {"in-base", "missing"} and "in-base" in edits and not deps_hold:
            done.append(t)
        elif "remote-gone" in edits:
            check.append(t)
        elif edits and edits <= {"new", "in-base", "missing"}:
            untouched.append(t)
    for t in done:
        if a.yes:
            remove_task(root, t, False)
        else:
            print(f"would remove {t}: every branch is already in its base")
    for t in check:
        print(f"check {t}: a remote branch is gone but its commits are not in the base - "
              "if its pull requests were squash-merged, wt.py remove --force")
    for t in untouched:
        print(f"kept {t}: nothing done in it yet - wt.py remove {t} if it is not needed")
    if not done and not check and not untouched:
        print("Nothing to prune.")
    elif done and not a.yes:
        print("Run again with --yes to remove them.")


