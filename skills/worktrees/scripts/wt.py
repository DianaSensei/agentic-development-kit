def main(argv=None):
    p = parser()
    a = p.parse_args(argv)
    try:
        return globals()["cmd_" + a.cmd](load_config(), a) or 0
    except Fail as e:
        print(f"wt.py: {e}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
