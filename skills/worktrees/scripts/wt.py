def cmd_repo(cfg, a):
    if a.repo_cmd == "add":
        path = os.path.realpath(os.path.expanduser(a.path))
        if not os.path.isdir(path) or not ok(path, "rev-parse", "--git-dir"):
            raise Fail(f"{a.path} is not a git checkout")
        entry = {"path": main_checkout(path)}
        if a.copy:
            entry["copy"] = a.copy
        if a.setup:
            entry["setup"] = a.setup
        update_config(cfg, lambda c: c["repos"].__setitem__(a.name, entry))
        print(f"{a.name} -> {entry['path']}")
    elif a.repo_cmd == "remove":
        if not update_config(cfg, lambda c: c["repos"].pop(a.name, None)):
            raise Fail(f"no repository named {a.name}")
        print(f"forgot {a.name} (its checkout and worktrees are untouched)")
    else:
        for name, e in sorted(cfg["repos"].items()):
            extra = "".join([f"  copy {','.join(e['copy'])}" if e.get("copy") else "",
                             f"  setup `{e['setup']}`" if e.get("setup") else ""])
            print(f"{name}  {e['path']}{extra}")


def valid_task_name(task):
    if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9._-]*", task):
        raise Fail(f"task name {task!r}: letters, digits, '.', '_' and '-' only - it is a folder name")


def create(root, meta, items, extras, do_fetch):
    d = task_dir(root, meta["task"])
    if os.path.exists(d):
        raise Fail(f"{d} already exists - wt.py add {meta['task']} <repo> to bring in another repository")
    if not items:
        raise Fail("a task needs at least one repository")
    meta["external_paths"] = extras
    check_extras(root, meta, extras)
    os.makedirs(d)
    print(f"task {meta['task']} at {d}")
    try:
        add_repos(root, meta, items, do_fetch)
        check_extras(root, meta, extras)          # again: now that the repositories have their names
        copy_extras(root, meta, extras)
    except BaseException:
        for name, r in meta["repositories"].items():
            git(r["source"], "worktree", "remove", "--force", os.path.join(d, name), check=False)
        shutil.rmtree(d, ignore_errors=True)
        raise
    save_task(root, meta)
    print(f"open it: cd {d}")


