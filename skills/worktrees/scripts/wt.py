#!/usr/bin/env python3
"""wt.py - task workspaces: one folder per task, holding a checkout of every repository the task needs.

    <root>/<task>/task.json      the manifest: each repository's role and version, the task's build and test
    <root>/<task>/<repo>/        a git worktree of <repo>'s main checkout
    <root>/<task>/checks.jsonl   every check: what ran, the result, and the commit of each repository it ran on

A repository has a role in a task:
    edit         a worktree on the task's branch, from the repository's base (REPO@BASE to pick one)
    dependency   a worktree detached at a pinned ref (REPO@REF: a tag, a branch, a commit), to build against

    wt.py init [--root PATH] [--sources PATH]          show or set the root, and where restore clones to
    wt.py repo add NAME PATH [--copy F]... [--setup CMD]
    wt.py repo list | repo remove NAME                 the repositories tasks can use, by name
    wt.py new TASK [REPO[@BASE]...] [--dep REPO[@REF]]... [--branch B] [--base REF] [--note TEXT]
              [--extra SRC[:DEST]]... [--build CMD]... [--test CMD]... [--no-fetch]
    wt.py restore MANIFEST [--as TASK] [--no-fetch]    rebuild a task from a task.json, on this machine or another
    wt.py add TASK [REPO[@BASE]...] [--dep REPO[@REF]]... [--no-fetch]
    wt.py pin TASK REPO REF [--no-fetch]               move a dependency to another ref
    wt.py refresh TASK                                 regenerate CLAUDE.md and task.env after editing task.json
    wt.py status [TASK...] [--fetch] [--json]          every task (or the named ones), and worktrees outside the root
    wt.py sync TASK [--rebase] [--no-fetch]            bring each edit repository up to date with its base
    wt.py run TASK [--all] -- CMD...                   a command in each edit repository (--all: dependencies too)
    wt.py check TASK [-- CMD...]                       the task's build and test, run together, and recorded
    wt.py remove TASK [--force]                        remove a task's worktrees and folder
    wt.py prune [--yes] [--no-fetch]                   remove tasks whose every branch is already in its base

Nothing that holds work is lost. `remove` refuses a repository with uncommitted changes or commits no
remote has; --force saves the uncommitted changes as a patch under <root>/.removed/<task>/ first, keeps a
branch with unpushed commits, and keeps the manifest there too, so `restore` can bring the task back.
Only worktrees under the root are ever removed.

Each task gets its own environment (task.env, and every command run/check/--setup starts): ADK_TASK,
ADK_TASK_DIR, ADK_TASK_CACHE (a cache folder of its own), ADK_PORT_OFFSET (unique among the root's
tasks), COMPOSE_PROJECT_NAME, and the manifest's own "env", which may use ${ADK_...}.

The root and the repository names live in ~/.config/adk/worktrees.json ($XDG_CONFIG_HOME respected;
ADK_WORKTREES_CONFIG and ADK_WORKTREES_ROOT override). Standard library only.
"""

import argparse
import json
import os
import re
import shlex
import shutil
import subprocess
import sys
import time

try:
    import fcntl
except ImportError:  # not on Windows: config writes are then unlocked
    fcntl = None

MANIFEST = "task.json"
LEGACY = ".adk-task.json"  # the manifest's name before 0.22
CHECKS = "checks.jsonl"
ENVFILE = "task.env"
CACHE = ".cache"
GENERATED = (MANIFEST, LEGACY, "CLAUDE.md", ENVFILE)
BEGIN = "<!-- adk-worktrees: generated by wt.py, refreshed on add and refresh; write your own notes outside this block -->"
END = "<!-- adk-worktrees:end -->"
FETCH_TIMEOUT = 120
ENV = dict(os.environ, GIT_TERMINAL_PROMPT="0")  # a fetch never waits on a credential prompt
SCRIPT = os.path.abspath(__file__)


class Fail(Exception):
    pass


# ---------------------------------------------------------------- git

def git(cwd, *args, check=True, timeout=None):
    r = subprocess.run(["git", "-C", cwd, *args], capture_output=True, text=True, env=ENV, timeout=timeout)
    if check and r.returncode:
        raise Fail(f"git {' '.join(args)} in {cwd}: {(r.stderr or r.stdout).strip()}")
    return r.stdout.strip() if check else r


def ok(cwd, *args):
    return git(cwd, *args, check=False).returncode == 0


def main_checkout(path):
    common = git(path, "rev-parse", "--path-format=absolute", "--git-common-dir")
    return os.path.dirname(common) if os.path.basename(common) == ".git" else common


def fetch(src):
    if "origin" not in git(src, "remote").split():
        return None
    try:
        r = git(src, "fetch", "--quiet", "--prune", "--tags", "origin", check=False, timeout=FETCH_TIMEOUT)
    except subprocess.TimeoutExpired:
        return f"fetch timed out after {FETCH_TIMEOUT}s - using what is already fetched"
    return None if r.returncode == 0 else f"fetch failed ({r.stderr.strip()[:200]}) - using what is already fetched"


def default_base(src):
    r = git(src, "symbolic-ref", "-q", "--short", "refs/remotes/origin/HEAD", check=False)
    if r.returncode == 0 and r.stdout.strip():
        return r.stdout.strip()
    for ref in ("origin/main", "origin/master", "main", "master"):
        if ok(src, "rev-parse", "-q", "--verify", ref + "^{commit}"):
            return ref
    return git(src, "rev-parse", "--abbrev-ref", "HEAD")


def resolve_ref(src, ref):
    """A ref as the team has it now: a branch name means origin's copy when there is one. -> (name, sha)."""
    name = f"origin/{ref}" if ok(src, "show-ref", "--verify", "-q", f"refs/remotes/origin/{ref}") else ref
    r = git(src, "rev-parse", "-q", "--verify", name + "^{commit}", check=False)
    return (name, r.stdout.strip()) if r.returncode == 0 else (None, None)


def origin_url(src):
    r = git(src, "remote", "get-url", "origin", check=False)
    return r.stdout.strip() if r.returncode == 0 else None


def same_url(a, b):
    norm = lambda u: re.sub(r"(\.git)?/*$", "", u.strip())
    return norm(a) == norm(b)


def count(cwd, *args):
    r = git(cwd, *args, check=False)
    return int(r.stdout.strip()) if r.returncode == 0 and r.stdout.strip().isdigit() else None


# ---------------------------------------------------------------- config

def config_path():
    if os.environ.get("ADK_WORKTREES_CONFIG"):
        return os.environ["ADK_WORKTREES_CONFIG"]
    base = os.environ.get("XDG_CONFIG_HOME") or os.path.join(os.path.expanduser("~"), ".config")
    return os.path.join(base, "adk", "worktrees.json")


def load_config():
    try:
        with open(config_path()) as f:
            cfg = json.load(f)
    except FileNotFoundError:
        cfg = {}
    cfg.setdefault("repos", {})
    for name, entry in list(cfg["repos"].items()):
        cfg["repos"][name] = {"path": entry} if isinstance(entry, str) else entry
    return cfg


def update_config(cfg, change):
    """Apply change() to the config as it is on disk now, under a lock: two sessions registering at once both land."""
    path = config_path()
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path + ".lock", "a") as lock:
        if fcntl:
            fcntl.flock(lock, fcntl.LOCK_EX)
        fresh = load_config()
        result = change(fresh)
        tmp = path + ".tmp"
        with open(tmp, "w") as f:
            json.dump(fresh, f, indent=2)
            f.write("\n")
        os.replace(tmp, path)
    cfg.clear()
    cfg.update(fresh)
    return result


def root_of(cfg):
    root = os.environ.get("ADK_WORKTREES_ROOT") or cfg.get("root")
    if not root:
        raise Fail("No worktree root is set. Ask the user where task folders should live, then run:\n"
                   "  wt.py init --root <path>")
    return os.path.realpath(os.path.expanduser(root))


def register(cfg, name, src):
    def change(c):
        known = c["repos"].get(name)
        if known and os.path.realpath(known["path"]) != src:
            raise Fail(f"the name {name} is already {known['path']} - register this one under another "
                       f"name: wt.py repo add <name> {src}")
        if not known:
            c["repos"][name] = {"path": src}
            return True
        return False
    if update_config(cfg, change):
        print(f"registered {name} -> {src}")
    return cfg["repos"][name]


def split_spec(arg):
    """REPO@REF -> (REPO, REF). A path that exists and holds an @ is a path."""
    if "@" in arg and not os.path.exists(os.path.expanduser(arg)):
        left, _, right = arg.rpartition("@")
        if left and right:
            return left, right
    return arg, None


def resolve_repo(cfg, arg):
    """A registered name, or a path to a checkout (registered by its folder name on first use)."""
    if arg in cfg["repos"]:
        entry = cfg["repos"][arg]
        if not os.path.isdir(entry["path"]):
            raise Fail(f"{arg}: its main checkout {entry['path']} is gone - wt.py repo add {arg} <new path>")
        return arg, entry
    path = os.path.realpath(os.path.expanduser(arg))
    if not os.path.isdir(path) or not ok(path, "rev-parse", "--git-dir"):
        have = ", ".join(sorted(cfg["repos"])) or "none yet"
        raise Fail(f"{arg}: not a registered repository ({have}) nor a path to a git checkout")
    src = main_checkout(path)
    name = os.path.basename(src)
    try:
        return name, register(cfg, name, src)
    except Fail as e:
        raise Fail(f"{arg}: {e}") from None


def locate(cfg, name, r):
    """Where a manifest's repository is on this machine: registered, at its recorded path, or cloned from its url."""
    url = r.get("url")
    if name in cfg["repos"]:
        entry = cfg["repos"][name]
        if not os.path.isdir(entry["path"]):
            raise Fail(f"{name}: its main checkout {entry['path']} is gone - wt.py repo add {name} <new path>")
        have = origin_url(entry["path"])
        if url and have and not same_url(have, url):
            raise Fail(f"{name}: registered here as {entry['path']}, whose origin is {have}, not {url} - "
                       f"register the right checkout: wt.py repo add {name} <path>")
        return entry
    src = r.get("source")
    if src and os.path.isdir(src) and ok(src, "rev-parse", "--git-dir"):
        src = main_checkout(src)
        have = origin_url(src)
        if not url or not have or same_url(have, url):
            return register(cfg, name, src)
    sources = cfg.get("sources")
    if url and sources:
        sources = os.path.realpath(os.path.expanduser(sources))
        dest = os.path.join(sources, name)
        if not os.path.exists(dest):
            os.makedirs(sources, exist_ok=True)
            print(f"  {name}: cloning {url} into {dest}")
            git(sources, "clone", "--quiet", url, dest)
        elif not ok(dest, "rev-parse", "--git-dir") or not same_url(origin_url(dest) or "", url):
            raise Fail(f"{name}: {dest} exists and is not a clone of {url}")
        return register(cfg, name, dest)
    if not url:
        raise Fail(f"{name}: not on this machine, and the manifest has no url for it - register its checkout: "
                   f"wt.py repo add {name} <path>")
    raise Fail(f"{name}: not on this machine - register its checkout (wt.py repo add {name} <path>), or set a "
               f"folder to clone {url} into (wt.py init --sources <path>)")


# ---------------------------------------------------------------- tasks

def task_dir(root, task):
    return os.path.join(root, task)


def is_task(path):
    return os.path.isfile(os.path.join(path, MANIFEST)) or os.path.isfile(os.path.join(path, LEGACY))


def normalize(meta):
    if "repositories" not in meta:          # 0.21: every repository on the task's branch
        meta["repositories"] = {n: dict(r, role="edit") for n, r in meta.pop("repos", {}).items()}
    for key, empty in (("external_paths", list), ("build", list), ("test", list), ("env", dict), ("runtime", dict)):
        meta.setdefault(key, empty())
    return meta


def load_task(root, task):
    d = task_dir(root, task)
    for name in (MANIFEST, LEGACY):
        try:
            with open(os.path.join(d, name)) as f:
                return normalize(json.load(f))
        except FileNotFoundError:
            continue
    raise Fail(f"no task {task} under {root}")


def all_tasks(root):
    if not os.path.isdir(root):
        return []
    return sorted(d for d in os.listdir(root) if not d.startswith(".") and is_task(os.path.join(root, d)))


def free_port_offset(root, task):
    used = set()
    for t in all_tasks(root):
        if t != task:
            used.add(load_task(root, t)["runtime"].get("port_offset"))
    n = 100
    while n in used:
        n += 100
    return n


def save_task(root, meta):
    d = task_dir(root, meta["task"])
    meta["runtime"].setdefault("port_offset", free_port_offset(root, meta["task"]))
    keys = ("task", "branch", "base", "note", "created", "repositories", "external_paths", "build", "test",
            "env", "runtime")
    ordered = {k: meta[k] for k in keys if k in meta}
    ordered.update({k: v for k, v in meta.items() if k not in ordered})
    with open(os.path.join(d, MANIFEST), "w") as f:
        json.dump(ordered, f, indent=2)
        f.write("\n")
    if os.path.exists(os.path.join(d, LEGACY)):
        os.remove(os.path.join(d, LEGACY))
    write_claude_md(root, meta)
    write_env(root, meta)


def task_env(root, meta):
    """The variables a task's commands run with: its own cache, ports and compose project, then the manifest's env."""
    d = task_dir(root, meta["task"])
    out = {"ADK_TASK": meta["task"], "ADK_TASK_DIR": d, "ADK_TASK_CACHE": os.path.join(d, CACHE),
           "ADK_PORT_OFFSET": str(meta["runtime"].get("port_offset", 0)),
           "COMPOSE_PROJECT_NAME": re.sub(r"[^a-z0-9_-]", "-", meta["task"].lower())}
    scope = dict(os.environ, **out)
    for k, v in meta.get("env", {}).items():
        v = re.sub(r"\$\{(\w+)\}|\$(\w+)", lambda m: scope.get(m.group(1) or m.group(2), m.group(0)), str(v))
        out[k] = scope[k] = v
    return out


def run_env(root, meta):
    os.makedirs(os.path.join(task_dir(root, meta["task"]), CACHE), exist_ok=True)
    return dict(os.environ, **task_env(root, meta))


def write_env(root, meta):
    lines = [f"# Task {meta['task']}'s environment - generated by wt.py; set your own in task.json \"env\", then",
             f"# wt.py refresh {meta['task']}. Use it for commands of your own: . ./{ENVFILE} && <command>"]
    lines += [f"export {k}={shlex.quote(v)}" for k, v in task_env(root, meta).items()]
    with open(os.path.join(task_dir(root, meta["task"]), ENVFILE), "w") as f:
        f.write("\n".join(lines) + "\n")


def version_of(r, branch):
    if r.get("role") == "dependency":
        return f"`{r['ref']}` (`{r['commit'][:10]}`)"
    return f"branch `{branch}`"


def write_claude_md(root, meta):
    """The task folder's CLAUDE.md: what the task is, each repository's role, and how to check it as a whole."""
    d = task_dir(root, meta["task"])
    task, repos = meta["task"], meta["repositories"]
    wt = "wt.py"
    owners = any(r.get("owner") for r in repos.values())
    lines = [BEGIN, f"# Task: {task}", ""]
    if meta.get("note"):
        lines += [meta["note"], ""]
    lines += ["This folder is the task's workspace, not a repository: run git per folder (`git -C <folder> ...`), "
              "and commit, push and open a pull request in each edit repository separately. The manifest is "
              f"`{MANIFEST}`.", "",
              "| Folder | Role | Version | Base |" + (" Owner |" if owners else ""),
              "|---|---|---|---|" + ("---|" if owners else "")]
    for name, r in repos.items():
        role = "dependency - do not edit" if r.get("role") == "dependency" else "edit"
        lines.append(f"| `{name}/` | {role} | {version_of(r, meta['branch'])} | "
                     f"{'`' + r['base'] + '`' if r.get('base') else '-'} |"
                     + (f" {r.get('owner') or '-'} |" if owners else ""))
    lines.append("")
    if any(r.get("role") == "dependency" for r in repos.values()):
        lines.append("- **Dependencies are pinned** for this task: read them and build against them, never change "
                     "them. A change one needs makes it an edit repository - ask first.")
    if owners:
        lines.append("- **Owners:** change only the folders you own; anything else goes back to whoever "
                     "coordinates the task.")
    check = (f"`{wt} check {task}` runs the manifest's build and test here, together, and records the "
             f"commit of every repository it ran on in `{CHECKS}`." if meta["build"] or meta["test"] else
             f"The manifest has no build or test commands yet: add them to `{MANIFEST}` (`\"build\"`, `\"test\"`), "
             f"then `{wt} check {task}`.")
    lines += [f"- **Check the task as a whole**, not one repository at a time: {check}",
              f"- **Commands of your own** (a server, a one-off test) run with the task's environment - its own "
              f"ports, compose project and cache folder: `. ./{ENVFILE} && <command>`.",
              f"- After editing `{MANIFEST}` by hand: `{wt} refresh {task}`.",
              f"- `wt.py` is the worktrees skill's script - `python3 {SCRIPT}` as of the last refresh; after the "
              "plugin updates, the skill's own folder has it."]
    imports = [f"@{name}/CLAUDE.md" for name in repos if os.path.isfile(os.path.join(d, name, "CLAUDE.md"))]
    if imports:
        lines += ["", "Each repository's own instructions:", *imports]
    block = "\n".join(lines + [END])
    path = os.path.join(d, "CLAUDE.md")
    try:
        with open(path) as f:
            text = f.read()
    except FileNotFoundError:
        text = ""
    if BEGIN in text and END in text:
        text = text[:text.index(BEGIN)] + block + text[text.index(END) + len(END):]
    elif "<!-- adk-worktrees:" in text and END in text:   # 0.21's block, under its older marker
        text = text[:text.index("<!-- adk-worktrees:")] + block + text[text.index(END) + len(END):]
    else:
        text = block + "\n" + (("\n" + text) if text else "")
    with open(path, "w") as f:
        f.write(text)


def copy_into(name, entry, path):
    for rel in entry.get("copy", []):
        s, d = os.path.join(entry["path"], rel), os.path.join(path, rel)
        if os.path.exists(s) and not os.path.exists(d):
            os.makedirs(os.path.dirname(d), exist_ok=True)
            (shutil.copytree if os.path.isdir(s) else shutil.copy2)(s, d)
            print(f"  {name}: copied {rel} from the main checkout")


def attach_edit(name, entry, path, branch, base):
    """Create the worktree on the task's branch; returns whether the branch was created here (so a rollback deletes it)."""
    src = entry["path"]
    if ok(src, "show-ref", "--verify", "-q", f"refs/heads/{branch}"):
        git(src, "worktree", "add", path, branch)
        created = False
    elif ok(src, "show-ref", "--verify", "-q", f"refs/remotes/origin/{branch}"):
        git(src, "worktree", "add", "--track", "-b", branch, path, f"origin/{branch}")
        created = True
    else:
        if not ok(src, "rev-parse", "-q", "--verify", base + "^{commit}"):
            raise Fail(f"{name}: base {base} does not exist")
        git(src, "worktree", "add", "--no-track", "-b", branch, path, base)
        created = True
    copy_into(name, entry, path)
    return created


def attach_dep(name, entry, path, ref, commit=None):
    """Create the worktree detached at the pinned commit; returns (ref, sha)."""
    src = entry["path"]
    if commit and ok(src, "cat-file", "-e", commit + "^{commit}"):
        sha = git(src, "rev-parse", commit + "^{commit}")
    else:
        resolved, sha = resolve_ref(src, ref)
        if not sha:
            raise Fail(f"{name}: {ref} does not exist")
        if commit:
            print(f"  {name}: the recorded commit {commit[:10]} is not here - using {resolved} at {sha[:10]}")
        ref = resolved
    git(src, "worktree", "add", "--detach", path, sha)
    copy_into(name, entry, path)
    return ref, sha


def setup(name, entry, path, env):
    if entry.get("setup"):
        print(f"  {name}: {entry['setup']}")
        if subprocess.run(entry["setup"], shell=True, cwd=path, env=env).returncode:
            print(f"  {name}: setup failed - the worktree is there; run it again by hand")


def plan(cfg, specs, role):
    out = []
    for spec in specs:
        arg, want = split_spec(spec)
        name, entry = resolve_repo(cfg, arg)
        out.append({"name": name, "entry": entry, "role": role, "want": want})
    return out


def add_repos(root, meta, items, do_fetch):
    """Attach each repository to the task, all or none: a failure removes what this call created."""
    d = task_dir(root, meta["task"])
    names = [i["name"] for i in items]
    for n in names:
        if n in meta["repositories"] or names.count(n) > 1:
            raise Fail(f"{n} is already in task {meta['task']}")
        if n in GENERATED or n in (CHECKS, CACHE) or any(e["destination"].split("/")[0] == n
                                                          for e in meta["external_paths"]):
            raise Fail(f"{n}: the task folder already uses that name")
    made = []
    try:
        for i in items:
            name, entry = i["name"], i["entry"]
            src = entry["path"]
            if do_fetch:
                warn = fetch(src)
                if warn:
                    print(f"  {name}: {warn}")
            path = os.path.join(d, name)
            record = {"role": i["role"], "url": origin_url(src), "source": src}
            if i.get("owner"):
                record["owner"] = i["owner"]
            if i["role"] == "dependency":
                ref, sha = attach_dep(name, entry, path, i["want"] or default_base(src), i.get("commit"))
                made.append((name, src, path, False))
                record.update(ref=ref, commit=sha)
                print(f"  {name}: {os.path.relpath(path, root)} pinned at {ref} ({sha[:10]})")
            else:
                base = i["want"] or meta.get("base") or default_base(src)
                made.append((name, src, path, attach_edit(name, entry, path, meta["branch"], base)))
                record.update(base=base, start=git(path, "rev-parse", "HEAD"))
                print(f"  {name}: {os.path.relpath(path, root)} on {meta['branch']} (base {base})")
            meta["repositories"][name] = record
    except Exception:
        for name, src, path, created in reversed(made):
            git(src, "worktree", "remove", "--force", path, check=False)
            if created:
                git(src, "branch", "-D", meta["branch"], check=False)
            meta["repositories"].pop(name, None)
        raise
    env = run_env(root, meta)
    for i in items:
        setup(i["name"], i["entry"], os.path.join(d, i["name"]), env)


def parse_extras(specs):
    out = []
    for spec in specs or []:
        src, _, dest = spec.partition(":")
        out.append({"source": src, "destination": dest or os.path.basename(os.path.normpath(src))})
    return out


def check_extras(root, meta, extras):
    d = task_dir(root, meta["task"])
    for e in extras:
        dest = os.path.normpath(os.path.join(d, e["destination"]))
        top = os.path.relpath(dest, d).split(os.sep)[0]
        if not dest.startswith(d + os.sep) or top in meta["repositories"] or top in GENERATED + (CHECKS, CACHE):
            raise Fail(f"{e['destination']}: not a free place inside the task folder")
        if not os.path.exists(os.path.expanduser(e["source"])):
            raise Fail(f"{e['source']}: not found")


def copy_extras(root, meta, extras):
    """External files and folders (sample data, local config) are copied, never linked: a task's tests write there."""
    d = task_dir(root, meta["task"])
    for e in extras:
        src, dest = os.path.expanduser(e["source"]), os.path.join(d, e["destination"])
        if os.path.exists(dest):
            print(f"  {e['destination']}: already there, kept")
            continue
        os.makedirs(os.path.dirname(dest), exist_ok=True)
        (shutil.copytree if os.path.isdir(src) else shutil.copy2)(src, dest)
        print(f"  {e['destination']}: copied from {e['source']}")


# ---------------------------------------------------------------- state

def edit_state(path, r):
    if not os.path.isdir(path):
        return {"role": "edit", "state": "missing"}
    base = r["base"]
    head = git(path, "rev-parse", "HEAD", check=False).stdout.strip()
    branch = git(path, "symbolic-ref", "-q", "--short", "HEAD", check=False).stdout.strip() or "(detached)"
    dirty = len(git(path, "status", "--porcelain", "--untracked-files=normal").splitlines())
    counts = git(path, "rev-list", "--left-right", "--count", f"{base}...HEAD", check=False)
    behind = ahead = None
    if counts.returncode == 0:
        behind, ahead = (int(x) for x in counts.stdout.split())
    if git(path, "remote").split():
        unpushed = count(path, "rev-list", "--count", "HEAD", "--not", "--remotes")
    else:
        unpushed = ahead
    track = git(path, "for-each-ref", "--format=%(upstream:short)|%(upstream:track)", f"refs/heads/{branch}",
                check=False).stdout.strip()
    upstream, _, t = track.partition("|")
    gone = "[gone]" in t
    if dirty:
        state = "uncommitted"
    elif unpushed and gone:
        state = "remote-gone"          # typical after a squash merge deleted the remote branch
    elif unpushed:
        state = "unpushed"
    elif ahead is None:
        state = "unknown"              # its base is gone: what the branch holds cannot be told
    elif ahead == 0 and head == r.get("start"):
        state = "new"                  # nothing done yet
    elif ahead == 0:
        state = "in-base"              # everything on the branch is already in its base
    else:
        state = "pushed"
    return {"role": "edit", "state": state, "head": head, "branch": branch, "ahead": ahead, "behind": behind,
            "uncommitted": dirty, "unpushed": unpushed, "upstream": upstream or None, "upstream_gone": gone,
            "base": base}


def dep_state(path, r):
    """A dependency's tracked files only: untracked files in it are what a build left there."""
    if not os.path.isdir(path):
        return {"role": "dependency", "state": "missing"}
    head = git(path, "rev-parse", "HEAD", check=False).stdout.strip()
    dirty = len(git(path, "status", "--porcelain", "--untracked-files=no").splitlines())
    unsaved = count(path, "rev-list", "--count", "HEAD", "--not", "--branches", "--remotes", "--tags") or 0
    state = "modified" if dirty else "moved" if head != r["commit"] else "pinned"
    return {"role": "dependency", "state": state, "head": head, "ref": r["ref"], "commit": r["commit"],
            "uncommitted": dirty, "unsaved": unsaved}


def repo_state(root, meta, name):
    r = meta["repositories"][name]
    path = os.path.join(task_dir(root, meta["task"]), name)
    return dep_state(path, r) if r.get("role") == "dependency" else edit_state(path, r)


def holds_work(s):
    if s["role"] == "dependency":
        return s["state"] != "missing" and (s["uncommitted"] or s["unsaved"])
    return s["state"] in ("uncommitted", "unpushed", "remote-gone", "unknown")


def last_check(root, task):
    try:
        with open(os.path.join(task_dir(root, task), CHECKS)) as f:
            lines = [l for l in f.read().splitlines() if l.strip()]
    except FileNotFoundError:
        return None
    return json.loads(lines[-1]) if lines else None


def changed_since(check, repos):
    then = check.get("repositories", {})
    return sorted(n for n, s in repos.items()
                  if n not in then or s.get("head") != then[n].get("commit")
                  or s.get("uncommitted") != then[n].get("uncommitted"))


def task_state(root, task, do_fetch=False):
    meta = load_task(root, task)
    out = {"task": task, "branch": meta["branch"], "note": meta.get("note"), "repos": {}}
    for name, r in meta["repositories"].items():
        if do_fetch and os.path.isdir(r["source"]):
            fetch(r["source"])
        out["repos"][name] = repo_state(root, meta, name)
    check = last_check(root, task)
    if check:
        out["last_check"] = {"at": check["at"], "result": check["result"],
                             "changed_since": changed_since(check, out["repos"])}
    return out


def strays(cfg, root):
    """Worktrees of registered repositories that are outside the root (the kit's own unit worktrees aside)."""
    found = []
    for name, entry in sorted(cfg["repos"].items()):
        src = entry["path"]
        if not os.path.isdir(src):
            continue
        for line in git(src, "worktree", "list", "--porcelain", check=False).stdout.splitlines():
            if not line.startswith("worktree "):
                continue
            p = os.path.realpath(line[9:])
            if p == os.path.realpath(src) or p.startswith(root + os.sep) or "/.claude/worktrees/" in p:
                continue
            found.append((name, p))
    return found


def fmt(v):
    return "-" if v is None else str(v)


