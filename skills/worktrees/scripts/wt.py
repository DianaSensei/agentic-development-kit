def cmd_pin(cfg, a):
    root = root_of(cfg)
    meta = load_task(root, a.task)
    r = meta["repositories"].get(a.repo)
    if not r or r.get("role") != "dependency":
        raise Fail(f"{a.repo} is not a dependency of {a.task}")
    s = repo_state(root, meta, a.repo)
    if s["state"] == "missing":
        raise Fail(f"{a.repo}: the folder is gone")
    if holds_work(s):
        raise Fail(f"{a.repo} holds changes of its own ({s['uncommitted']} uncommitted, {s['unsaved']} commit(s) "
                   "on no branch) - a dependency is not edited; move them out first")
    if not a.no_fetch:
        warn = fetch(r["source"])
        if warn:
            print(f"  {a.repo}: {warn}")
    ref, sha = resolve_ref(r["source"], a.ref)
    if not sha:
        raise Fail(f"{a.repo}: {a.ref} does not exist")
    git(os.path.join(task_dir(root, a.task), a.repo), "checkout", "-q", "--detach", sha)
    r.update(ref=ref, commit=sha)
    save_task(root, meta)
    print(f"  {a.repo}: pinned at {ref} ({sha[:10]}) - check the task again: wt.py check {a.task}")


